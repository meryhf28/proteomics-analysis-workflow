# Optional functional-module smoke tests: run from the public repository root.
# Synthetic input only. Exercises parsing, accession mapping and functional plot export.
if (!requireNamespace("ggplot2", quietly=TRUE)) stop("Install ggplot2")
tmp <- tempfile("annotation-tests-"); dir.create(tmp)
source_file <- file.path(tmp,"egg.tsv")
writeLines(c("## eggNOG-mapper synthetic fixture", "#query\tDescription", "P00001\tProtein description one", "P00002\tProtein description two"),source_file)
run_script <- function(filename, params) {
  cmd <- file.path(R.home("bin"), "Rscript")
  if (.Platform$OS.type == "windows") cmd <- paste0(cmd, ".exe")
  args <- c(shQuote(filename), vapply(params, shQuote, character(1)))
  status <- system2(cmd,args=args, stdout=TRUE, stderr=TRUE)
  if (!is.null(attr(status,"status")) && attr(status,"status") != 0L) stop(paste(status,collapse="\n"))
}
map <- file.path(tmp,"map.csv")
run_script("scripts/import_eggnog.R",c(source_file,map))
x <- utils::read.csv(map,stringsAsFactors=FALSE)
stopifnot(nrow(x)==2L,identical(x$accession,c("P00001","P00002")),all(is.na(x$category)))
x$category <- c("Metabolism","Unknown function")
utils::write.csv(x,map,row.names=FALSE)
input <- data.frame(accession=c("P00001","P00002","P00003"),log2FC=c(2,-1,0.9),FDR=c(0.005,0.02,0.04))
sig <- file.path(tmp,"significant.csv"); utils::write.csv(input,sig,row.names=FALSE)
joined <- file.path(tmp,"annotated.csv")
run_script("scripts/merge_annotations.R",c(sig,map,joined))
y <- utils::read.csv(joined,stringsAsFactors=FALSE)
stopifnot(nrow(y)==3L,all(y$category[1:2]==x$category),is.na(y$category[3]))
prefix <- file.path(tmp,"category_plot")
run_script("scripts/plot_annotations.R",c(joined,prefix))
stopifnot(file.exists(paste0(prefix,"_functional_categories.png")),file.exists(paste0(prefix,"_category_counts.csv")))
unlink(tmp, recursive=TRUE)
message("PASS: synthetic eggNOG import, curated merge, missing-annotation retention and functional barplot.")
